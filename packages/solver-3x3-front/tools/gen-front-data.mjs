// Writes res/FrontData.res from tools/front-model.mjs. Usage: node tools/gen-front-data.mjs [--check]
// --check compares the committed file with the generated text and exits 1 when they differ.
import fs from "node:fs";
import { CORNER_FACELET, EDGE_FACELET, turnTables, rotations, shortWords } from "./front-model.mjs";

const here = new URL("../res/FrontData.res", import.meta.url);
const arr = (name, v, note) => `// ${note}\nlet ${name}: array<int> = [${v.join(", ")}]\n`;
const strs = (name, v, note) => `// ${note}\nlet ${name}: array<string> = [${v.map((s) => JSON.stringify(s)).join(", ")}]\n`;

export function generate() {
  const t = turnTables();
  const rots = rotations();
  return [
    "// GENERATED by tools/gen-front-data.mjs from tools/front-model.mjs; do not edit. tests check it against a fresh derivation.\n",
    arr("cornerFacelet", CORNER_FACELET.flat(), "8 corner slots x 3 facelets (cubie.rs CORNER_FACELET)"),
    arr("edgeFacelet", EDGE_FACELET.flat(), "12 edge slots x 2 facelets (cubie.rs EDGE_FACELET)"),
    arr("cfrom", t.cfrom, "18 turns x 8: after turn m, corner slot t holds what slot cfrom[m*8+t] held (m = 3 * face + q, faces URFDLB)"),
    arr("cadd", t.cadd, "18 turns x 8: its twist grew by cadd"),
    arr("efrom", t.efrom, "18 turns x 12: as cfrom for edge slots"),
    arr("eadd", t.eadd, "18 turns x 12: its flip grew by eadd"),
    arr("rotMap", rots.flatMap((r) => r.map), "24 rotations x 54: sticker i goes to position rotMap[r*54+i]; identity first, breadth first over x y z"),
    arr("rotDest", rots.flatMap((r) => r.dest), "24 x 6: the center of face g sits on face rotDest[r*6+g]"),
    arr("rotAdd", rots.flatMap((r) => r.add), "24 x 6: its picture is turned this many more quarters"),
    strs("rotWord", rots.map((r) => r.word), "the raw word of x y z quarter turns of each rotation"),
    strs("rotShort", shortWords(rots), "the answer spelling: at most two tokens x y z with suffix ' or 2"),
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = generate();
  if (process.argv.includes("--check")) {
    if (fs.readFileSync(here, "utf8") !== text) { console.error("res/FrontData.res is out of date"); process.exit(1); }
  } else fs.writeFileSync(here, text);
}
